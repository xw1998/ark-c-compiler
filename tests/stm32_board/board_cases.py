"""Test programs for the on-board (STM32H743) run of arkcc.

Every case is a complete single-file C program whose `main` returns an int.
The board's `run <file>` compiles the file in place and prints
`[arkcc] program returned <n>`, so the return value is the reading -- no
printf, no formatting layer, nothing between the program and the measurement.

The sources are copied verbatim from the x86-64 flat-image gate
(tests/run_x86_64_image_tests.py), whose expected values were computed outside
that program (by hand or by a Python expression over the same inputs).  Reusing
them is deliberate: the numbers are already vetted, and a case that agrees on
x86-64 and disagrees here is a backend difference, not a test that was tuned to
whatever the board happened to print.

The variadic cases are not in this list: they need <stdarg.h>, which the board
only has if the header is uploaded into a RAM slot (see run_stm32_board_tests.py
--varargs).  Everything else here needs no header at all.
"""

